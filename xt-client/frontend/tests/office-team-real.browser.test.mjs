import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {mkdtemp, readFile, mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {test} from 'node:test';
import {chromium} from 'playwright';
import {Vector3} from 'three';
import {createCamera} from '../src/features/office/scene-geometry.ts';

test('real service team persistence and 3D interactions', {timeout: 120000}, async context => {
  const root = await mkdtemp(join(tmpdir(), 'xiaotao-team-real-'));
  const data = join(root, 'data');
  const project = join(root, 'project');
  await mkdir(project);
  const output = resolve('test-results');
  await mkdir(output, {recursive: true});
  let server;
  let preview;
  let browser;
  let page;
  let base = '';
  let log = '';
  try {
    server = spawn('go', ['run', '../cmd/xiaotao', '--data-dir', data, '--service'], {stdio: ['ignore', 'pipe', 'pipe']});
    server.stderr.on('data', chunk => {log += chunk;});
    for (let attempt = 0; attempt < 100; attempt++) {
      try {base = JSON.parse(await readFile(join(data, 'runtime.json'), 'utf8')).URL; break;} catch {await new Promise(done => setTimeout(done, 100));}
    }
    assert.ok(base, `service did not start: ${log}`);
    preview = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '5239', '--strictPort'],
      {env: {...process.env, XIAOTAO_DEV_API: base}, stdio: ['ignore', 'pipe', 'pipe']});
    await Promise.race([new Promise(resolve => preview.stdout.on('data', data => {if (data.toString().includes('ready in')) resolve();})), once(preview, 'exit').then(() => {throw Error('Vite exited before ready');})]);
    const response = await fetch(base + '/api/agent/projects', {method: 'POST', headers: {'Content-Type': 'application/json', Origin: base}, body: JSON.stringify({path: project, name: '真实验收项目'})});
    assert.equal(response.status, 200);
    browser = await chromium.launch({channel: process.env.XIAOTAO_TEST_BROWSER || 'msedge', headless: true, args: ['--enable-unsafe-swiftshader']});
    page = await browser.newPage({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
    await page.route('**/api/agent/models', route => route.fulfill({json: {models: [{model: 'test/model', label: '团队测试模型', contextWindow: 128000, maxOutputTokens: 8192}]}}));
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => {if (message.type() === 'error') errors.push(message.text());});
    await page.goto('http://127.0.0.1:5239');
    await page.locator('.workspace-dock').getByRole('button', {name: '办公室', exact: true}).click();
    await page.locator('[data-entry-phase=ready]').waitFor();
    await page.getByRole('button', {name: '组建小队', exact: true}).click();
    await page.getByRole('button', {name: '稍后设置', exact: true}).click();
    if (!await page.getByRole('tab', {name: /团队/}).isVisible()) await page.getByRole('button', {name: '任务', exact: true}).click();
    await page.getByRole('tab', {name: /团队/}).click();
    await page.locator('.workspace-team').getByRole('button', {name: '管理团队', exact: true}).click();
    await page.getByRole('heading', {name: '建立项目团队'}).waitFor();
    await page.screenshot({path: join(output, 'team-create-real.png')});
    const createResponse = page.waitForResponse(response => response.url().endsWith('/api/office/team/bootstrap'));
    await page.getByRole('button', {name: '创建可编辑小队'}).click();
    assert.equal((await createResponse).status(), 200);
    await page.locator('.team-member-list h3').filter({hasText: '设计'}).waitFor();
    let team = await (await fetch(`${base}/api/office/team?projectPath=${encodeURIComponent(project)}`)).json();
    assert.equal(team.members.length, 3);
    const originalId = team.members[0].id;
    const teamYaml = await readFile(join(project, '.xiaotao', 'team.yaml'), 'utf8');
    const rolesYaml = await readFile(join(project, '.xiaotao', 'roles', 'registry.yaml'), 'utf8');
    assert.match(teamYaml, /role_id: role_[a-f0-9]{16}/);
    assert.match(rolesYaml, /primary_color: '#[a-f0-9]{6}'/);
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({state: 'detached'});
    await page.locator('canvas[data-office-renderer="three"]').waitFor({timeout: 10000}).catch(async reason => {
      const entry = page.locator('.office-entry-flow');
      const phase = await entry.getAttribute('data-entry-phase');
      const body = (await page.locator('body').innerText()).slice(0, 1200);
      throw new Error(`3D load failed: entry=${phase}; text=${body}; ${errors.join(' | ')}; ${reason.message}`);
    });
    await page.locator('.room-tool').filter({hasText: '成员4'}).waitFor();
    await page.screenshot({path: join(output, 'office-team-real.png')});
    const bounds = await page.locator('canvas[data-office-renderer="three"]').boundingBox();
    // The first employee sits behind the left desk, separate from the coordinator.
    const point = new Vector3(.78, 2.18, 1.42).project(createCamera(bounds.width, bounds.height));
    await page.mouse.click(bounds.x + (point.x + 1) * bounds.width / 2, bounds.y + (1 - point.y) * bounds.height / 2);
    await page.getByRole('heading', {name: /与.*对话/}).waitFor();
    await page.getByRole('button', {name: '返回团队成员', exact: true}).click();
    await page.getByRole('button', {name: '管理团队', exact: true}).click();
    await page.getByRole('button', {name: '编辑', exact: true}).first().click();
    const editor = page.getByRole('dialog', {name: '管理团队'});
    await editor.getByLabel('姓名', {exact: true}).fill('真实产品设计师');
    await editor.locator('textarea').fill('负责真实需求与交互设计');
    await editor.getByRole('button', {name: '人物造型'}).click();
    await page.getByRole('option', {name: '六边形'}).click();
    await editor.locator('input[type="color"]').first().fill('#123456');
    const updateResponse = page.waitForResponse(response => response.url().endsWith('/api/office/roles') && response.request().method() === 'PUT');
    await page.getByRole('button', {name: '保存角色', exact: true}).click();
    const savedRole = await updateResponse;
    assert.equal(savedRole.status(), 200, await savedRole.text());
    await page.getByText('真实产品设计师', {exact: true}).waitFor();
    team = await (await fetch(`${base}/api/office/team?projectPath=${encodeURIComponent(project)}`)).json();
    assert.equal(team.members[0].id, originalId);
    assert.equal(team.members[0].responsibility, '负责真实需求与交互设计');
    assert.equal(team.members[0].appearance.primaryColor, '#123456');
    assert.equal(team.members[0].appearance.shape, 'hexagon');
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({state: 'detached'});
    await page.getByRole('button', {name: '收起协作面板'}).click();
    await page.getByRole('button', {name: '放大视角', exact: true}).click();
    await page.getByRole('button', {name: '复位视角', exact: true}).click();
    await page.getByRole('button', {name: '打开项目资料馆', exact: true}).first().click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.reload();
    await page.locator('.workspace-dock').getByRole('button', {name: '办公室', exact: true}).click();
    if (!await page.getByRole('tab', {name: /团队/}).isVisible()) await page.getByRole('button', {name: '任务', exact: true}).click();
    await page.getByRole('tab', {name: /团队/}).click();
    await page.locator('.workspace-member-list [data-member-id]').filter({hasText: '真实产品设计师'}).waitFor();
    await page.locator('.workspace-member-list [data-member-id]').filter({hasText: '真实产品设计师'}).click();
    await page.getByRole('heading', {name: /与.*对话/}).waitFor();
    await page.getByRole('button', {name: '返回团队成员', exact: true}).click();
    const snapshot = await (await fetch(`${base}/api/office/snapshot?projectPath=${encodeURIComponent(project)}`)).json();
    assert.equal(snapshot.members.find(member => member.id === originalId).responsibility, '负责真实需求与交互设计');
    assert.equal(snapshot.members.find(member => member.id === originalId).status, 'idle');
    await page.setViewportSize({width: 600, height: 900});
    await page.locator('.workspace-member-list [data-member-id]').filter({hasText: '真实产品设计师'}).click();
    await page.getByRole('heading', {name: /与.*对话/}).waitFor();
    await page.getByRole('button', {name: '返回团队成员', exact: true}).click();
    await page.setViewportSize({width: 800, height: 900});
    assert.ok(await page.locator('.workspace-grid').evaluate(element => {
      const [scene, panel] = element.children;
      const room = scene.getBoundingClientRect();
      const drawer = panel.getBoundingClientRect();
      return Math.abs(room.right - drawer.right) <= 2 && drawer.width < room.width;
    }), 'narrow office keeps the drawer over the right side of the full-width room');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'narrow office must not overflow horizontally');
    await page.evaluate(() => {document.querySelector('.office-live-page').scrollTop = 0;});
    const sidebar = await page.locator('.workspace-sidebar').boundingBox();
    const statusbar = await page.locator('.workspace-statusbar').boundingBox();
    assert.ok(sidebar.y + sidebar.height <= statusbar.y, 'the status bar must not cover the member list');
    await page.screenshot({path: join(output, 'office-team-real-mobile.png')});
    const name = page.locator('.workspace-member-list [data-member-id]').filter({hasText: '真实产品设计师'}).locator('strong');
    assert.ok(await name.evaluate(element => element.getBoundingClientRect().height <= 24), 'member name and role must stay on one line');
    assert.ok(await name.locator(':scope > span').evaluate(element => element.getBoundingClientRect().width >= 80), 'member name must retain a readable column');
    assert.deepEqual(errors, []);
    context.diagnostic(`真实团队已保存到 ${project}；截图位于 ${output}`);
  } finally {
    await page?.screenshot({path: join(output, 'office-team-real-failure.png')}).catch(() => {});
    await browser?.close();
    preview?.kill();
    if (base) await fetch(base + '/api/shutdown', {method: 'POST', headers: {Authorization: `Bearer ${JSON.parse(await readFile(join(data, 'runtime.json'), 'utf8')).Token}`}}).catch(() => {});
    server?.kill();
  }
});
