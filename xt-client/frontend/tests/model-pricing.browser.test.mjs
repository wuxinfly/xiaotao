import assert from 'node:assert/strict';
import {test} from 'node:test';
import {fillSource, saveSource, sourceBrowser} from './source-browser-fixture.mjs';

test('manual model capabilities and limits remain usable in narrow views and keyboard dialogs', {timeout:60000}, () => sourceBrowser(5198, async ({page,state,errors,navigate}) => {
  await navigate('accounts');
  await page.getByRole('heading', {name:'添加第一个模型接口'}).waitFor();
  await fillSource(page, 'Custom endpoint');
  await page.getByLabel('模型 1 上下文窗口').fill('65536');
  await page.getByLabel('模型 1 最大输出').fill('4096');
  await page.getByRole('checkbox', {name:'支持图片'}).check();
  await page.getByRole('checkbox', {name:'支持推理'}).check();
  await page.getByLabel('模型 1 推理档位').fill('low, high');
  await page.setViewportSize({width:540,height:800});
  const dialog=await page.getByRole('dialog').boundingBox();
  assert.ok(dialog.x>=0 && dialog.x+dialog.width<=540);
  await saveSource(page);
  await navigate('agent');
  await page.getByRole('button', {name:'打开 Agent 设置'}).click();
  await page.getByRole('checkbox',{name:'Shared model · Custom endpoint',exact:true}).click();
  await page.getByRole('button',{name:'调整 Shared model 参数'}).click();
  assert.equal(await page.getByLabel('Shared model 上下文窗口').inputValue(),'65536');
  assert.equal(await page.getByLabel('Shared model 最大输出').inputValue(),'4096');
  await page.getByLabel('Shared model 思考等级').selectOption('high');
  await page.getByRole('button', {name:/默认模型/}).click();
  await page.getByRole('combobox',{name:'AI 重命名模型'}).click();
  await page.getByRole('option',{name:/Shared model/}).click();
  assert.equal(await page.getByLabel('AI 重命名最大输出').inputValue(),'4096');
  await page.getByRole('button', {name:'保存设置',exact:true}).click();
  const configs=await page.evaluate(() => JSON.parse(localStorage.getItem('xiaotao.agent.modelConfigs')));
  assert.equal(configs[0].maxOutputTokens,4096);
  assert.equal(configs[0].reasoningEffort,'high');
  await navigate('accounts');
  await page.getByRole('article', {name:'Custom endpoint'}).getByRole('button', {name:'编辑',exact:true}).click();
  await page.getByLabel('来源名称').fill('Unsaved');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', {name:'编辑模型接口',exact:true}).waitFor({state:'hidden'});
  assert.equal(state.sources[0].label,'Custom endpoint');
  await page.getByRole('heading', {name:'本地调用入口'}).waitFor();
  assert.equal(await page.locator('.model-sources-page').evaluate(element => element.scrollWidth > element.clientWidth),false);
  assert.deepEqual(errors,[]);
}));
